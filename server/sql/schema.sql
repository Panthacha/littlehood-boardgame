-- Little Hood: Into the Woods — history/reporting schema.
-- Run this once in the Supabase project's SQL editor (Project > SQL Editor > New query).
-- This only stores HISTORY (final results per finished session). Live gameplay state
-- stays in the Node server's memory; nothing here is read during an active round.

create table if not exists events (
  event_slug text primary key,
  created_at timestamptz not null default now()
);

create table if not exists game_sessions (
  id text primary key, -- matches the in-memory Session.id generated by the server
  event_slug text not null references events(event_slug),
  started_at timestamptz not null default now(),
  finished_at timestamptz
);

create table if not exists house_results (
  id bigint generated always as identity primary key,
  session_id text not null references game_sessions(id),
  house_id integer not null,
  score integer not null,
  correct_answers integer not null,
  role text, -- werewolf-phase role, if night mode was played
  is_dead boolean,
  recorded_at timestamptz not null default now(),
  unique (session_id, house_id)
);

create index if not exists idx_game_sessions_event_slug on game_sessions(event_slug);
create index if not exists idx_house_results_session_id on house_results(session_id);
